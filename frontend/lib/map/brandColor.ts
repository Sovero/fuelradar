/**
 * Цвет «кольца сети» вокруг маркера (R103) — отдельный визуальный слой ПОВЕРХ
 * заливки статуса топлива (R27/R28, которую не трогаем). Официальные цвета
 * брендов АЗС не ищем — пользователь явно оставил палитру на наше усмотрение;
 * вместо хардкода цвета под каждую сеть по имени (сетей может быть много и не
 * все известны заранее — см. `/meta` → `station_brands`) детерминированно
 * хэшируем название сети в цвет из фиксированной палитры. Независимые станции
 * (пустой/отсутствующий brand) — без кольца вообще, это их отличительный вид.
 */

const PALETTE = [
  "#2563eb", // синий
  "#7c3aed", // фиолетовый
  "#db2777", // розовый
  "#0891b2", // бирюзовый
  "#4f46e5", // индиго
  "#0d9488", // тил
  "#92400e", // коричневый
  "#475569", // сине-серый
  "#e11d48", // малиновый
  "#a855f7", // пурпурный
];

/** Простой стабильный хэш строки (без внешних зависимостей). */
function hashString(value: string): number {
  let hash = 0;
  for (let i = 0; i < value.length; i++) {
    hash = (hash * 31 + value.charCodeAt(i)) >>> 0;
  }
  return hash;
}

export function brandRingColor(brand: string | null | undefined): string | null {
  const name = (brand ?? "").trim();
  if (!name) return null;
  return PALETTE[hashString(name) % PALETTE.length];
}
