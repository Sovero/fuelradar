export type TranslationKey = keyof (typeof dict)["ru"];

export function translate(locale: Locale, key: TranslationKey): string {
  return dict[locale]?.[key] ?? dict[DEFAULT_LOCALE][key] ?? key;
}

/** Подстановка {token} в переведённый шаблон — для строк с интерполяцией (например empty.headline). */
export function translateTemplate(locale: Locale, key: TranslationKey, values: Record<string, string | number>): string {
  const template = translate(locale, key);
  return Object.entries(values).reduce((acc, [token, value]) => acc.replaceAll(`{${token}}`, String(value)), template);
}
